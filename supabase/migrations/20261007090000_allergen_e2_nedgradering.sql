-- Én opdatering pr. produkt (flere flag på samme produkt samles), kun hvor den gamle værdi stadig står.
, matched as (
  select c.id::uuid as id, jsonb_object_agg(c.allergen, c.new_v) as patch
  from changes c
  join public.products p on p.id = c.id::uuid and p.allergen_flags->>c.allergen = c.old_v
  group by c.id
)
update public.products p
set allergen_flags = p.allergen_flags || m.patch
from matched m
where p.id = m.id;
